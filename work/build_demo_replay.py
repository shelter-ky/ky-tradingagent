"""Create a portable UI example using synthetic prices and signals and the actual ledger."""
import json

import numpy as np
import pandas as pd

from demo_ledger import MAIN, ROOT, replay, rules


def demo_sessions():
    days={}
    previous=100.0
    for i,dt in enumerate(pd.bdate_range("2025-08-04","2025-08-29")):
        day=str(dt.date())
        grid=pd.date_range(day+" 09:30",periods=390,freq="min",tz="America/New_York")
        direction=(.014,-.021,-.012,.023,.009)[i%5]
        path=1+direction*np.linspace(0,1,len(grid))+.001*np.sin(np.arange(len(grid))/25)
        q=previous*path
        t=(55+i*.11)*(1+3*(path-1))
        days[day]=dict(prices=(grid,t,float(t[-1])),qqq_prices=(grid,q,float(q[-1])),closes=t,qcloses=q,
                       split=1.,scale=1.,vxn=(17.,19.,23.,18.,16.)[i%5],vxn_reference=20.,
                       gate=True,pre="MISSING",prefix=len(grid),pm_valid=True,qcut=q[-11],qvwap=q[:-10].mean(),
                       prev_q_close=previous,old_sell={32} if direction<0 else set(),old_buy={120} if direction>0 else set(),
                       sell={40},buy={55})
        previous=float(q[-1])
    return days


def main():
    days=demo_sessions()
    data={"demo":True,"initial":7000,"dates":list(days),"symbols":{},
          "market":[[v["vxn"],20,"MISSING",390,390] for v in days.values()]}
    day_index={date:i for i,date in enumerate(days)}
    for symbol in ("TQQQ","QQQ"):
        accounts={}
        for rule in rules():
            if rule.name not in MAIN:
                continue
            fills,marks,_=replay(days,symbol,rule,0,{"TQQQ":{},"QQQ":{}},record_targets=True)
            accounts[rule.family]={"daily":marks[["equity","cash","qty","close","receivable","unrealized"]].round(7).values.tolist(),
                                   "targets":[list(t.values()) for t in marks.targets],
                                   "orders":[[day_index[o.date],o.et[11:16],o.delta,round(o.price,7),o.fee,
                                              None if pd.isna(o.closed_pnl) else round(o.closed_pnl,7)]
                                             for o in fills.itertuples()]}
        data["symbols"][symbol]=accounts
    target=ROOT/"量化交易台"/"回放数据.js"
    target.write_text("// Synthetic demonstration generated by work/build_demo_replay.py.\nwindow.REPLAY = "+json.dumps(data,allow_nan=False,separators=(",",":"))+";\n",encoding="utf-8")


if __name__=="__main__":
    main()
